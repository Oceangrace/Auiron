const projectRules = {
  rules: {
    'explicit-if-comparison': {
      meta: {
        type: 'problem',
        schema: [],
        messages: {
          comparison: 'Условие if должно использовать === / !== или их объединение через && / ||.',
        },
      },
      create(context) {
        return {
          IfStatement(node) {
            const conditions = [node.test];

            while (conditions.length !== 0) {
              const condition = conditions.pop();

              if (condition === undefined) {
                continue;
              }

              if (
                condition.type === 'LogicalExpression' &&
                (condition.operator === '&&' || condition.operator === '||')
              ) {
                conditions.push(condition.left, condition.right);
                continue;
              }

              if (
                condition.type === 'BinaryExpression' &&
                (condition.operator === '===' || condition.operator === '!==')
              ) {
                continue;
              }

              context.report({ node: condition, messageId: 'comparison' });
            }
          },
        };
      },
    },
  },
};

